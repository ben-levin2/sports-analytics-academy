def _data_picker(key):
    up = datasets.status("rate_events")
    variant = None
    if up["source"] == "simulated":
        variant = st.selectbox("Dataset", list(datasets.SPECS["rate_events"].simulated), key=f"{key}_variant")
    df, info = datasets.load("rate_events", variant)
    if info["source"] == "simulated":
        ui.sim_banner(f"{info['label']}: fictional players generated by academy/data.py. "
                      "Upload real data on the Data Sources page to replace it.")
    else:
        st.success(f"Using your data: {info['label']} ({len(df)} rows, "
                   f"{'marked real' if info['real'] else 'not marked real'}).")
    if info.get("error"):
        st.warning(f"Configured dataset ignored: {info['error']}")
    labels = LABELS.get(info["label"], ("successes", "opportunities", "rate"))
    has_pos = "position" in df.columns and df["position"].nunique() > 1
    group = None
    if has_pos:
        group = "position" if st.radio("Prior", ["One prior for everyone", "Separate prior per position"],
                                       index=1, horizontal=True, key=f"{key}_group").startswith("Separate") else None
    return df, info, labels, group


def _player_chart(a0, b0, k, n, pop, labels):
    post = stats.beta(a0 + k, b0 + n - k)
    prior = stats.beta(a0, b0)
    like = stats.beta(k + 1, n - k + 1)
    lo = max(0.0, min(prior.ppf(0.001), post.ppf(0.001), like.ppf(0.005)) - 0.02)
    hi = min(1.0, max(prior.ppf(0.999), post.ppf(0.999), like.ppf(0.995)) + 0.02)
    x = np.linspace(lo, hi, 600)
    fig, ax = plt.subplots(figsize=(7.5, 3.6))
    ax.plot(x, prior.pdf(x), color=T.MUTED, ls="--", lw=2, label="Prior (population)")
    ax.plot(x, like.pdf(x), color=T.AMBER, lw=2, label="Likelihood (his data only)")
    ax.plot(x, post.pdf(x), color=T.BLUE, lw=2.8, label="Posterior")
    ax.fill_between(x, post.pdf(x), color=T.BLUE, alpha=0.18)
    ax.axvline(k / n, color=T.AMBER, ls=":", lw=1.6, label=f"Raw {labels[2]} {k / n:.3f}")
    ax.axvline(pop, color=T.TEXT, lw=1, label=f"Population average {pop:.3f}")
    ax.set_xlabel(f"True {labels[2]}"), ax.set_yticks([]), ax.legend(loc="upper right", fontsize=8)
    return fig, post


def _uncertainty_chart(a0, b0, raw, n_player, labels):
    ns = np.unique(np.geomspace(1, 2000, 80).astype(int))
    k = raw * ns
    a, b = a0 + k, b0 + ns - k
    mean = a / (a + b)
    lo, hi = stats.beta.ppf(0.025, a, b), stats.beta.ppf(0.975, a, b)
    fig, ax = plt.subplots(figsize=(7.5, 3.0))
    ax.fill_between(ns, lo, hi, color=T.BLUE, alpha=0.2, label="95% credible interval")
    ax.plot(ns, mean, color=T.BLUE, lw=2, label="Posterior mean")
    ax.axhline(raw, color=T.AMBER, ls=":", lw=1.4, label=f"His raw {labels[2]} (held fixed)")
    ax.axhline(a0 / (a0 + b0), color=T.TEXT, lw=1, label="Prior mean")
    ax.axvline(n_player, color=T.ROSE, lw=1.2, ls="--", label=f"His actual volume ({n_player})")
    ax.axvline(a0 + b0, color=T.GREEN, lw=1, ls="-.", label=f"Prior strength ({a0 + b0:.0f}): 50/50 weight")
    ax.set_xscale("log"), ax.set_xlabel(f"Opportunities ({labels[1]})"), ax.set_ylabel(labels[2])
    ax.legend(loc="best", fontsize=7.5)
    return fig


def _shrink_scatter(tab, pop, labels):
    fig, ax = plt.subplots(figsize=(7.5, 3.4))
    sc = ax.scatter(tab["raw_rate"], tab["post_mean"], c=np.log10(tab["opportunities"]), s=10, cmap="cool", alpha=0.8)
    lim = [tab["raw_rate"].quantile(0.005), tab["raw_rate"].quantile(0.995)]
    ax.plot(lim, lim, color=T.MUTED, ls="--", lw=1, label="No shrinkage (y = x)")
    ax.axhline(pop, color=T.TEXT, lw=1, label="Population average")
    ax.set_xlim(lim), ax.set_xlabel(f"Raw {labels[2]}"), ax.set_ylabel(f"Posterior mean {labels[2]}")
    cb = plt.colorbar(sc, ax=ax)
    cb.set_label("log10(opportunities)", color=T.MUTED)
    ax.legend(loc="upper left", fontsize=8)
    return fig


def learning_lab(project):
    state = ui.get_state()
    df, info, labels, group = _data_picker("p1lab")
    priors = _priors(df, group)
    tab = S.posterior_table(df, priors, group)

    st.markdown("#### 1 · The prior, fitted from every player (empirical Bayes)")
    rows = [{"group": g if g != "__all__" else "everyone", "prior mean": a / (a + b),
             "prior strength (pretend opportunities)": a + b} for g, (a, b) in priors.items()]
    st.dataframe(pd.DataFrame(rows).round(4), hide_index=True)
    st.caption("Chosen by maximizing the marginal likelihood across all player-seasons (lesson L1.5). "
               "Strength = how many opportunities of evidence the population average is worth.")

    st.markdown("#### 2 · One player: raw stat → prior → likelihood → posterior")
    tab = tab.sort_values("opportunities")
    low = tab[(tab["opportunities"] < tab["opportunities"].quantile(0.25)) & (tab["raw_rate"] > tab["prior_mean"])]
    default = low.iloc[len(low) // 2]["player_id"] if len(low) else tab.iloc[0]["player_id"]
    ids = tab["player_id"].tolist()
    names = {r.player_id: f"{r.player_id} · {getattr(r, group) + ' · ' if group else ''}"
                          f"{int(r.successes)}/{int(r.opportunities)}" for r in tab.itertuples()}
    if st.session_state.get("p1_player") not in names:
        st.session_state["p1_player"] = default
    c1, c2 = st.columns([2, 1])
    pid = c1.selectbox("Player (sorted by volume)", ids, key="p1_player", format_func=names.get)
    c2.write("")
    c2.button("Show a high-volume player", key="p1_high", on_click=st.session_state.__setitem__,
              args=("p1_player", ids[-max(1, len(ids) // 20)]))
    r = tab.set_index("player_id").loc[pid]
    a0, b0 = S.prior_for(priors, r[group] if group else "__all__")
    k, n = int(r["successes"]), int(r["opportunities"])
    pop = a0 / (a0 + b0)
    fig, post = _player_chart(a0, b0, k, n, pop, labels)
    ui.show_fig(fig)
    lo, hi = post.ppf([0.025, 0.975])
    m = st.columns(5)
    m[0].metric(f"Raw {labels[2]}", f"{k / n:.3f}", f"{k} / {n}", delta_color="off")
    m[1].metric("Population average", f"{pop:.3f}")
    m[2].metric("Posterior mean", f"{post.mean():.3f}")
    m[3].metric("95% credible interval", f"{lo:.3f}–{hi:.3f}")
    m[4].metric("Weight on his data", f"{n / (n + a0 + b0):.0%}")
    st.caption(f"Posterior mean = {n / (n + a0 + b0):.0%} × raw rate + {(a0 + b0) / (n + a0 + b0):.0%} × population average.")

    st.markdown("#### 3 · How uncertainty changes with more observations")
    ui.show_fig(_uncertainty_chart(a0, b0, k / n, n, labels))
    st.caption("Same raw rate, more and more volume. The interval narrows like 1/√n (lesson L1.6), and the posterior "
               "moves from the prior toward his raw rate. They meet halfway at the prior strength.")

    st.markdown("#### 4 · Every player at once")
    ui.show_fig(_shrink_scatter(tab, df["successes"].sum() / df["opportunities"].sum(), labels))
    st.caption("Low-volume players (pink) are pulled hard toward the average. High-volume players (cyan) stay near the diagonal.")

    st.markdown("#### 5 · Leaderboards")
    min_n = st.slider("Minimum opportunities to appear", 1, 200, 1, key="p1_minn")
    shown = tab[tab["opportunities"] >= min_n]
    cols = (["player_id"] + ([group] if group else []) + ["successes", "opportunities", "raw_rate", "post_mean", "ci_low", "ci_high"])
    l1, l2 = st.columns(2)
    l1.markdown("**Top 10 by raw rate**")
    l1.dataframe(shown.sort_values("raw_rate", ascending=False).head(10)[cols].round(3), hide_index=True)
    l2.markdown("**Top 10 by posterior mean**")
    l2.dataframe(shown.sort_values("post_mean", ascending=False).head(10)[cols].round(3), hide_index=True)


def production_candidate(project):
    state = ui.get_state()
    df, info, labels, group = _data_picker("p1prod")
    if st.button("▶ Run rolling-origin evaluation", type="primary", key="p1_eval"):
        st.session_state["p1_eval_args"] = (info["label"], group)
    if st.session_state.get("p1_eval_args") != (info["label"], group):
        st.caption("The metric, baselines and gates are fixed in code before any data is evaluated.")
        return
    res = _evaluate(df, group)
    gl = S.gates(res, info)
    verdict = S.verdict(gl)
    rec = state["projects"].get(project.id, {})
    last = rec.get("runs", [{}])[-1] if rec.get("runs") else {}
    if last.get("verdict") != f"{verdict} [{info['label']}{', by position' if group else ''}]":
        progress.log_project_run(state, project.id, project.title,
                                 f"{verdict} [{info['label']}{', by position' if group else ''}]")

    (st.success if verdict.startswith("Meets") else st.warning)(f"**Verdict: {verdict}**")
    ui.html("".join(f'<div class="aa-gate"><span>{"✅" if ok else "❌"}</span><span><b>{ui.esc(name)}</b><br>'
                    f'<span class="d">{ui.esc(detail)}</span></span></div>' for name, ok, detail in gl))
    if not res.get("ok"):
        return

    o = res["overall"]
    m = st.columns(4)
    m[0].metric("Baseline: raw past rate", f"{o['raw']:.5f}")
    m[1].metric("Baseline: population/position mean", f"{o['population']:.5f}")
    m[2].metric("Shrinkage model", f"{o['model']:.5f}", f"{res['gain']:+.1%} vs best baseline")
    m[3].metric(f"{S.INTERVAL:.0%} interval coverage", f"{res['coverage']:.1%}")

    per = res["per_season"]
    fig, ax = plt.subplots(figsize=(7.5, 3.0))
    for col, c, lab in [("raw", T.AMBER, "Raw past rate"), ("population", T.MUTED, "Population mean"), ("model", T.BLUE, "Shrinkage")]:
        ax.plot(per["season"], per[col], marker="o", color=c, lw=2, label=lab)
    ax.set_xlabel("Test season (trained only on earlier seasons)"), ax.set_ylabel("Weighted MSE"), ax.legend(fontsize=8)
    ui.show_fig(fig)
    st.dataframe(per.rename(columns={"test_rows": "player-seasons"}).round(6), hide_index=True)
    st.caption("Concept 26: each row is one rolling-origin fold. Everything used to predict season T "
               "was computed from seasons before T, and this is checked on every fold.")

    st.markdown("#### Probability check: P(top-third season next year) · concept 25")
    pr = res["prob"]
    st.caption(S.EVENT)
    m = st.columns(4)
    m[0].metric("Brier score", f"{pr['brier']:.3f}", f"base rate {pr['brier_base']:.3f}", delta_color="off")
    m[1].metric("Brier skill vs base rate", f"{pr['skill']:+.1%}")
    m[2].metric("Calibration error (ECE)", f"{pr['ece']:.3f}", f"gate <= {S.MAX_ECE}", delta_color="off")
    m[3].metric("AUC: model vs 'same as last season'", f"{pr['auc_model']:.3f} vs {pr['auc_last_season']:.3f}")
    t = pr["reliability"]
    fig, ax = plt.subplots(figsize=(5.5, 3.2))
    ax.plot([0, 1], [0, 1], color=T.MUTED, ls="--", lw=1.2, label="Perfect calibration")
    ax.plot(t["predicted"], t["observed"], marker="o", color=T.BLUE, lw=2.2, label="Shrinkage model")
    ax.set_xlim(0, 1), ax.set_ylim(0, 1), ax.set_xlabel("Forecast probability"), ax.set_ylabel("Observed frequency")
    ax.legend(loc="upper left", fontsize=8)
    ui.show_fig(fig)
    st.caption(f"{pr['n']} qualifying player-seasons; {pr['event_rate']:.0%} had a top-third season. "
               "The forecast assumes his next-season volume is known (it predicts the rate, not the playing time). "
               "AUC is reported for comparison with your Model 9 baseline; it is not a gate.")
    st.caption("Passing every gate is necessary, not sufficient. Before using a result, check that the test seasons "
               "look like the seasons you care about, and that nothing changed in how the stat is recorded.")
