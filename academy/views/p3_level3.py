def _load(spec_id, key):
    src = datasets.status(spec_id)
    variant = None
    if src["source"] == "simulated":
        variant = st.selectbox("Dataset", list(datasets.SPECS[spec_id].simulated), key=f"{key}_variant")
    df, info = datasets.load(spec_id, variant)
    if info["source"] == "simulated":
        ui.sim_banner(f"{info['label']}: fictional data generated by academy/data.py. "
                      "Upload your own CSV on the Data Sources page to replace it.")
    else:
        st.success(f"Using your data: {info['label']} ({len(df)} rows, "
                   f"{'marked real' if info['real'] else 'not marked real'}).")
    if info.get("error"):
        st.warning(f"Configured dataset ignored: {info['error']}")
    return df, info


def _gates(gl, verdict):
    (st.success if verdict.startswith("Meets") else st.warning)(f"**Verdict: {verdict}**")
    ui.html("".join(f'<div class="aa-gate"><span>{"✅" if ok else "❌"}</span><span><b>{ui.esc(name)}</b><br>'
                    f'<span class="d">{ui.esc(detail)}</span></span></div>' for name, ok, detail in gl))


def _log(project, tag):
    state = ui.get_state()
    runs = state["projects"].get(project.id, {}).get("runs", [])
    if not runs or runs[-1]["verdict"] != tag:
        progress.log_project_run(state, project.id, project.title, tag)


def _reliability(t):
    fig, ax = plt.subplots(figsize=(5.5, 3.0))
    ax.plot([0, 1], [0, 1], color=T.MUTED, ls="--", lw=1.2, label="Perfect calibration")
    ax.plot(t["predicted"], t["observed"], marker="o", color=T.BLUE, lw=2.2, label="Model")
    ax.set_xlim(0, 1), ax.set_ylim(0, 1), ax.set_xlabel("Forecast"), ax.set_ylabel("Observed"), ax.legend(fontsize=8)
    ui.show_fig(fig)


# =================================================================== 3A: survival
@st.cache_data(show_spinner=False)
def _cox(df, outcome):
    d = df.copy()
    event = d["contributed"] if outcome == "contrib" else d.get("left_before_contributing", 1 - d["contributed"])
    positions = sorted(d["position"].unique()) if "position" in d.columns else None
    X, names = S.design(d, positions=positions)
    if not X.shape[1]:
        return None, names, positions
    return S.cox_fit(X, d["seasons_observed"], event), names, positions


@st.cache_data(show_spinner="Running the class-by-class evaluation…")
def _eval_surv(df):
    return S.evaluate_contribution(df)


def survival_lab(project):
    df, info = _load("roster_careers", "p3alab")
    has_left = "left_before_contributing" in df.columns
    outcome = st.radio("Outcome", ["First contribution (300+ snap season)", "Left the roster before contributing"],
                       horizontal=True, key="p3a_outcome", disabled=not has_left)
    key = "contrib" if outcome.startswith("First") else "left"
    event = df["contributed"] if key == "contrib" else df["left_before_contributing"]
    label = "contributed" if key == "contrib" else "left"

    st.markdown("#### 1 · Kaplan-Meier vs the naive answers (L3.3)")
    km = S.kaplan_meier(df["seasons_observed"], event)
    naive_share = float(event.mean())
    naive_time = float(df.loc[event == 1, "seasons_observed"].mean())
    m = st.columns(3)
    m[0].metric(f"Kaplan-Meier: {label} by season 3", f"{1 - S.km_at(km, 3):.0%}")
    m[1].metric(f"Naive raw share who {label}", f"{naive_share:.0%}", help="Treats censored players as 'never'")
    m[2].metric("Naive average time (events only)", f"{naive_time:.2f} seasons", help="Ignores everyone still waiting")

    st.markdown("#### 2 · Compare groups")
    opts = [c for c in ("rating tier", "position") if (c == "rating tier" and "recruit_rating" in df.columns)
            or (c == "position" and "position" in df.columns)]
    by = st.radio("Split by", opts or ["(none available)"], horizontal=True, key="p3a_by")
    if by == "rating tier":
        groups = pd.qcut(df["recruit_rating"], 3, labels=["bottom third", "middle third", "top third"])
    elif by == "position":
        groups = df["position"]
    else:
        groups = pd.Series("all", index=df.index)
    fig, ax = plt.subplots(figsize=(7.5, 3.4))
    for (g, d), c in zip(df.groupby(groups, observed=True), T.CYCLE * 3):
        k = S.kaplan_meier(d["seasons_observed"], event[d.index])
        ax.step(np.r_[0, k["time"]], np.r_[0, 1 - k["survival"]], where="post", color=c, lw=2, label=str(g))
        ax.fill_between(np.r_[0, k["time"]], np.r_[0, 1 - k["hi"]], np.r_[0, 1 - k["lo"]], step="post", color=c, alpha=0.12)
    ax.set_xlabel("Seasons since enrolling"), ax.set_ylabel(f"Share who have {label}"), ax.set_ylim(0, 1)
    ax.legend(fontsize=7, ncol=2)
    ui.show_fig(fig)
    st.caption("Shaded bands are 95% Greenwood confidence intervals. They widen where few players are still at risk.")

    st.markdown("#### 3 · Cox model (L3.4)")
    model, names, _ = _cox(df, key)
    if model is None:
        st.info("Needs recruit_rating and/or position columns to fit a Cox model.")
        return
    hr = pd.DataFrame({"trait": names, "hazard ratio": np.exp(model["beta"]),
                       "95% low": np.exp(model["beta"] - 1.96 * model["se"]),
                       "95% high": np.exp(model["beta"] + 1.96 * model["se"])})
    hr["clear effect?"] = np.where((hr["95% low"] > 1) | (hr["95% high"] < 1), "yes", "no (interval includes 1)")
    st.dataframe(hr.round(2), hide_index=True)

    if "recruit_rating" in df.columns:
        st.markdown("#### 4 · Proportional-hazards check")
        X, _ = S.design(df)
        e1 = ((event == 1) & (df["seasons_observed"] == 1)).astype(int)
        hr1 = float(np.exp(S.cox_fit(X, np.minimum(df["seasons_observed"], 1), e1)["beta"][0]))
        later = (df["seasons_observed"] >= 2).to_numpy()
        hr2 = float(np.exp(S.cox_fit(X[later], df.loc[later, "seasons_observed"] - 1, event[later])["beta"][0]))
        c1, c2 = st.columns(2)
        c1.metric("Rating hazard ratio, season 1", f"{hr1:.2f}")
        c2.metric("Rating hazard ratio, seasons 2+", f"{hr2:.2f}")
        st.caption("If these differ a lot, one hazard ratio for all seasons is misleading.")


def survival_prod(project):
    df, info = _load("roster_careers", "p3aprod")
    if st.button("▶ Run class-by-class evaluation", type="primary", key="p3a_eval"):
        st.session_state["p3a_eval_args"] = info["label"]
    if st.session_state.get("p3a_eval_args") != info["label"]:
        st.caption("Metric, baseline and gates are fixed in code before any data is evaluated.")
        return
    res = _eval_surv(df)
    gl = S.gates(res, info)
    verdict = S.verdict(gl)
    _log(project, f"{verdict} [{info['label']}]")
    _gates(gl, verdict)
    if not res.get("ok"):
        return
    b = res["brier"]
    m = st.columns(4)
    m[0].metric("Brier: one overall rate", f"{b['overall']:.4f}")
    m[1].metric("Brier: rating-tier baseline", f"{b['baseline']:.4f}")
    m[2].metric("Brier: Cox model", f"{b['cox']:.4f}", f"{res['gain']:+.1%} vs baseline")
    m[3].metric("AUC: Cox vs baseline", f"{res['auc_cox']:.3f} vs {res['auc_baseline']:.3f}")
    st.dataframe(res["per_class"].round(4), hide_index=True)
    st.markdown("**Calibration of P(contributes by season 2)**")
    _reliability(res["reliability"])
    st.caption("Each class is predicted at enrollment from earlier classes, with their outcomes cut off at the season "
               "before it arrived. A small edge over the tier baseline is real but small; report it as such.")


# =================================================================== 3B: Kriging
@st.cache_data(show_spinner="Fitting the Kriging map…")
def _map(df, name, nu, target):
    y = df[target] - df[target].mean()
    gp = SP.fit_gp(df[["lon", "lat"]], y, name, nu)
    gx, gy, G = SP.grid(df)
    mu, sd = SP.predict_latent(gp, G)
    return gx, gy, mu.reshape(gx.shape), sd.reshape(gx.shape), str(gp.kernel_), float(gp.log_marginal_likelihood_value_)


@st.cache_data(show_spinner="Running the class-by-class map test…")
def _eval_map(df, name, nu):
    return SP.evaluate_spatial(df, name, nu)


def _kernel_pick(key):
    c1, c2 = st.columns(2)
    name = c1.radio("Kernel", ["Matern", "RBF"], horizontal=True, key=f"{key}_k")
    nu = 1.5
    if name == "Matern":
        nu = c2.select_slider("Matérn roughness ν", [0.5, 1.5, 2.5], 1.5, key=f"{key}_nu")
    return name, nu


def spatial_lab(project):
    df, info = _load("hometowns", "p3blab")
    st.markdown("#### 1 · Where recruits come from vs how they perform")
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.4))
    hb = axes[0].hexbin(df["lon"], df["lat"], gridsize=26, cmap="viridis", mincnt=1)
    plt.colorbar(hb, ax=axes[0]), axes[0].set_title("Player counts", fontsize=9)
    hb2 = axes[1].hexbin(df["lon"], df["lat"], C=df["production"], gridsize=26, cmap="coolwarm", mincnt=8,
                         reduce_C_function=np.mean)
    plt.colorbar(hb2, ax=axes[1]), axes[1].set_title("Average production (cells with 8+ players)", fontsize=9)
    for a in axes:
        a.grid(False)
    ui.show_fig(fig)

    st.markdown("#### 2 · Kriging map (L3.8)")
    name, nu = _kernel_pick("p3blab")
    target = "production"
    if "recruit_rating" in df.columns and st.toggle("Map production NOT explained by recruit rating",
                                                     value=True, key="p3b_resid"):
        d = df.copy()
        b = np.polyfit(d["recruit_rating"], d["production"], 1)
        d["rating_adjusted"] = d["production"] - np.polyval(b, d["recruit_rating"])
        df, target = d, "rating_adjusted"
    gx, gy, mu, sd, kern, lml = _map(df, name, nu, target)
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.4))
    cf = axes[0].contourf(gx, gy, mu, 14, cmap="coolwarm", vmin=-6, vmax=6)
    plt.colorbar(cf, ax=axes[0]), axes[0].set_title("Kriged average vs national mean", fontsize=9)
    cf2 = axes[1].contourf(gx, gy, sd, 14, cmap="magma")
    plt.colorbar(cf2, ax=axes[1]), axes[1].set_title("Uncertainty of that average (SD)", fontsize=9)
    for a in axes:
        a.grid(False)
    ui.show_fig(fig)
    st.caption(f"Fitted kernel: `{kern}`. Log marginal likelihood {lml:.1f} (higher = fits better; compare kernels).")

    st.markdown("#### 3 · Variogram")
    vg = SP.empirical_variogram(df, target)
    fig, ax = plt.subplots(figsize=(7, 2.6))
    ax.plot(vg["distance"], vg["semivariance"], marker="o", color=T.BLUE, lw=2)
    ax.set_xlabel("Distance between hometowns (degrees)"), ax.set_ylabel("Semivariance")
    ui.show_fig(fig)
    st.caption("A flat line means nearby players are no more alike than distant ones (no regional pattern). "
               "A rising line means there is one.")

    st.markdown("#### 4 · Regions: more players, or better players?")
    t = SP.regional_table(df, 5.0)
    st.dataframe(t.round(3), height=260)
    st.caption("Big 'players' with an ordinary 'mean_production' = population, not talent. "
               "Always read the standard error: small regions have big ones.")


