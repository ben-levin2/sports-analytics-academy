"""Level 2 project: Player Archetype Discovery (interactive Learning Lab + automated Production Candidate)."""
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import streamlit as st
from sklearn.metrics import adjusted_rand_score

from .. import archetypes as A, datasets, progress, theme as T, ui


@st.cache_data(show_spinner=False)
def _silhouettes(Z, ks):
    return A.silhouette_by_k(Z, ks)


@st.cache_data(show_spinner="Running rolling-origin archetype test…")
def _evaluate(df, features, k, group, min_snaps):
    return A.evaluate_downstream(df, list(features), k, group, min_snaps)


def _controls(key):
    src = datasets.status("player_profiles")
    variant = None
    if src["source"] == "simulated":
        variant = st.selectbox("Dataset", list(datasets.SPECS["player_profiles"].simulated), key=f"{key}_variant")
    df, info = datasets.load("player_profiles", variant)
    if info["source"] == "simulated":
        ui.sim_banner(f"{info['label']}: fictional players generated by academy/data.py. "
                      "Upload real profiles on the Data Sources page to replace it.")
    else:
        st.success(f"Using your data: {info['label']} ({len(df)} rows, "
                   f"{'marked real' if info['real'] else 'not marked real'}).")
    cands = A.feature_candidates(df)
    c1, c2 = st.columns(2)
    group = None
    if "position_group" in df.columns:
        g = c1.selectbox("Position group", ["All"] + sorted(df["position_group"].dropna().unique()), index=1,
                         key=f"{key}_group")
        group = None if g == "All" else g
    min_snaps = 0
    if "snaps" in df.columns:
        min_snaps = c2.slider("Minimum snaps", 0, 400, 150, 25, key=f"{key}_snaps",
                              help="Per-snap stats from tiny samples are mostly noise (lesson L1.6).")
    features = st.multiselect("Features", cands, default=cands, key=f"{key}_feats")
    return df, info, group, min_snaps, features


def learning_lab(project):
    df, info, group, min_snaps, features = _controls("p2lab")
    if len(features) < 2:
        st.warning("Pick at least two features.")
        return
    d = A.prepare(df, features, group, min_snaps)
    if len(d) < 30:
        st.warning("Fewer than 30 players after filtering. Lower the minimum snaps or choose a bigger group.")
        return
    st.caption(f"{len(d)} player-seasons after filtering.")

    st.markdown("#### 1 · Standardize (L2.1)")
    scaler, Z = A.standardize(d, features)
    st.dataframe(pd.DataFrame({"raw mean": d[features].mean(), "raw SD": d[features].std(),
                               "standardized mean": Z.mean(0), "standardized SD": Z.std(0)}).round(3))
    st.caption("After standardizing, every stat has mean 0 and SD 1, so weight can't swamp pressure rate.")

    st.markdown("#### 2 · Choose k (L2.2)")
    ks = tuple(range(2, 9))
    sil = _silhouettes(Z, ks)
    fig, ax = plt.subplots(figsize=(7, 2.5))
    ax.plot(list(sil), list(sil.values()), marker="o", color=T.BLUE, lw=2)
    ax.set_xlabel("k"), ax.set_ylabel("Silhouette")
    ui.show_fig(fig)
    best = max(sil, key=sil.get)
    k = st.slider("k (your choice)", 2, 8, best, key="p2_k",
                  help=f"Silhouette prefers k = {best}. Football meaning and stability matter too.")
    km = A.fit_kmeans(Z, k)
    stab = A.stability(Z, k)
    m = st.columns(3)
    m[0].metric("Silhouette at your k", f"{sil[k]:.3f}")
    m[1].metric("Stability across restarts (ARI)", f"{stab:.2f}", help="1 = identical every time")
    if "true_archetype" in d.columns:
        m[2].metric("Match to hidden truth (ARI)", f"{adjusted_rand_score(d['true_archetype'], km.labels_):.2f}",
                    help="Only possible because the data is simulated")

    st.markdown("#### 3 · The map (PCA latent space)")
    xy, ev = A.pca_2d(Z)
    color_by = st.radio("Color by", ["Cluster", "Listed position"], horizontal=True, key="p2_color")
    labels = km.labels_ if color_by == "Cluster" else d["position"].to_numpy()
    fig, ax = plt.subplots(figsize=(7.5, 3.6))
    for i, lab in enumerate(sorted(pd.unique(labels), key=str)):
        mask = labels == lab
        ax.scatter(xy[mask, 0], xy[mask, 1], s=8, alpha=0.65, color=T.CYCLE[i % 6],
                   label=f"cluster {lab}" if color_by == "Cluster" else str(lab))
    ax.set_xlabel(f"Hidden dimension 1 ({ev[0]:.0%})"), ax.set_ylabel(f"Hidden dimension 2 ({ev[1]:.0%})")
    ax.legend(fontsize=7, markerscale=2)
    ui.show_fig(fig)

    st.markdown("#### 4 · Name the clusters from their profiles")
    prof = A.profiles(d, km.labels_, features)
    st.dataframe(prof.style.background_gradient(cmap="coolwarm", subset=features, vmin=-1.5, vmax=1.5)
                 .format("{:.2f}", subset=features))
    st.caption("Each number is how far the cluster sits from the average player, in standard deviations. "
               "Big positive or negative values are what define the cluster.")
    names = {}
    cols = st.columns(min(k, 4))
    for c in range(k):
        names[c] = cols[c % len(cols)].text_input(f"Name for cluster {c}", key=f"p2_name_{group}_{k}_{c}",
                                                  placeholder="e.g. Edge rusher")

    st.markdown("#### 5 · Discovered archetypes vs listed positions")
    lab = pd.Series(km.labels_).map(lambda c: names.get(c) or f"cluster {c}")
    st.dataframe(pd.crosstab(lab.rename("archetype"), d["position"].rename("listed position")))
    st.caption(f"Agreement between clusters and listed positions (ARI): "
               f"{adjusted_rand_score(d['position'], km.labels_):.2f}. Low agreement isn't a failure: "
               "it means the label hides different styles.")
    ui.html('<div class="aa-takeaway"><span class="aa-label">Remember</span><br>'
            "These clusters are descriptive discoveries: they say who plays alike. Whether they help predict "
            "anything is a separate question, tested in the Production Candidate tab.</div>")


def production_candidate(project):
    state = ui.get_state()
    df, info, group, min_snaps, features = _controls("p2prod")
    k = st.number_input("k (fix it before running; that's your registration)", 2, 8, 3, key="p2_prod_k")
    if not {"production", "next_production"} <= set(df.columns):
        st.warning("This dataset has no `production` / `next_production` columns, so the predictive test can't run. "
                   "Its archetypes stay descriptive (Learning Lab).")
        return
    args = (info["label"], tuple(features), int(k), group, min_snaps)
    if st.button("▶ Run rolling-origin archetype test", type="primary", key="p2_eval"):
        st.session_state["p2_eval_args"] = args
    if st.session_state.get("p2_eval_args") != args:
        st.caption("Metric, baseline and gates are fixed in code before any data is evaluated.")
        return
    if len(features) < 2:
        st.warning("Pick at least two features.")
        return
    res = _evaluate(df, tuple(features), int(k), group, min_snaps)
    gl = A.gates(res, info)
    verdict = A.verdict(gl)
    tag = f"{verdict} [{info['label']}, {group or 'all'}, k={int(k)}]"
    runs = state["projects"].get(project.id, {}).get("runs", [])
    if not runs or runs[-1]["verdict"] != tag:
        progress.log_project_run(state, project.id, project.title, tag)

    (st.success if verdict.startswith("Meets") else st.warning)(f"**Verdict: {verdict}**")
    ui.html("".join(f'<div class="aa-gate"><span>{"✅" if ok else "❌"}</span><span><b>{ui.esc(name)}</b><br>'
                    f'<span class="d">{ui.esc(detail)}</span></span></div>' for name, ok, detail in gl))
    if not res.get("ok"):
        return
    mae = res["mae"]
    m = st.columns(3)
    m[0].metric("'Same as last season' MAE", f"{mae['same_as_last']:.2f}")
    m[1].metric("Baseline (production + position)", f"{mae['baseline']:.2f}")
    m[2].metric("With archetypes", f"{mae['archetypes']:.2f}", f"{res['gain']:+.1%} vs baseline")
    per = res["per_season"]
    fig, ax = plt.subplots(figsize=(7.5, 2.8))
    for col, c, lab in [("same_as_last", T.MUTED, "Same as last season"), ("baseline", T.AMBER, "Baseline"),
                        ("archetypes", T.BLUE, "With archetypes")]:
        ax.plot(per["season"], per[col], marker="o", color=c, lw=2, label=lab)
    ax.set_xlabel("Test season (predicting the following season)"), ax.set_ylabel("MAE"), ax.legend(fontsize=8)
    ui.show_fig(fig)
    st.dataframe(per.round(3), hide_index=True)
    st.caption("If archetypes fail here, they can still be useful descriptions. They just haven't earned a place in a forecast.")
